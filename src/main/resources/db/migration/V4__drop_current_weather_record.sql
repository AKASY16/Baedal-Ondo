-- 초단기실황 저장 테이블을 지운다.
--
-- 현재 점수의 날씨는 실황이 아니라 예보를 쓴다. 실황은 매시 40분에야 제공되어
-- 그 전까지는 직전 시각 관측밖에 없고, 그러면 시간대·대기질 점수와 기준 시각이 어긋난다.
-- 예보로 옮기면서 이 테이블에 쓰던 경로가 전부 끊겼고, 읽는 코드도 함께 지웠다.
--
-- 과거 관측이 다시 필요해지면 기상청 ASOS로 소급해 받을 수 있으므로 여기에 쌓아 둘 이유가 없다.
-- 그때는 용도에 맞는 스키마를 새로 만드는 편이 낫다. 이 테이블은 발표분 기준(nx, ny,
-- base_date, base_time)으로만 유일해서 소급 조회에 필요한 관측 시각을 담지 못한다.
DROP TABLE IF EXISTS `current_weather_record`;
